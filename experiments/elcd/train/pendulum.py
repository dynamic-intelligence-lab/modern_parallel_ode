"""A damped planar n-link pendulum: long, physical demonstrations of any length.

State (theta, theta_dot) with theta_i the absolute angle of link i from the downward vertical. With link lengths
l_i, masses m_i and gravity g, both bodies of the literature have kinetic energy T = theta_dot^T M(theta)
theta_dot / 2 with M_ij = W_ij l_i l_j cos(theta_i - theta_j) and potential V = g sum_i w_i l_i (1 - cos theta_i):

  point masses at the link ends (massless rods):  W_ij = mu_max(i,j), w_i = mu_i, mu_i = sum_{k >= i} m_k;
  uniform rods:  W_ij = m_max(i,j) / 2 + nu_max(i,j) (i != j), W_ii = m_i / 3 + nu_i, w_i = m_i / 2 + nu_i,
                 nu_i = sum_{k > i} m_k (the rod's own inertia m l^2 / 12 is in W_ii).

Lagrange's equations then read M(theta) theta_ddot + C(theta) theta_dot^2 + G(theta) + R(theta_dot) = 0 with
C_ij = W_ij l_i l_j sin(theta_i - theta_j) (squared velocities elementwise), G_i = g w_i l_i sin theta_i, and the
damping R either "absolute" (R_i = b theta_dot_i, a torque against each link's rotation in the inertial frame) or
"joint" (R_i = b (w_i - w_{i-1}) - b (w_{i+1} - w_i) with w = theta_dot and w_0 = 0, a torque at every joint
against the relative rotation). The energy E = T + V obeys dE/dt = -theta_dot^T R <= 0 and is conserved at b = 0.
`simulate` integrates by classical RK4 at a sub-step of dt / SUBSTEPS and samples every dt.

`fit_paper` fits the body, the damping model and the parameters (lengths, masses, damping; g fixed at 9.81, since
(l, g, b) -> (c l, c g, c^2 b) and (m, b) -> (c m, c b) leave the motion unchanged) to the ELCD paper's data
(PAPER_DIR/n-{2,4,8}.npz, keys my_X_phy and my_X_dot_phy, (T, n_demos, 2 n) at
dt 0.1) by least squares on the acceleration part of the velocity residual (the position part, theta_dot, is the
state itself in that data). PAPER_MODEL records what the fit found (python experiments/elcd/train/pendulum.py on a CPU), and
the 'npend' demonstrations use it at any link count.

'npend:<links>-N<n>[-b<damping>]' (load_npend): 7 demonstrations (3 training) of n samples at dt 0.005 from
initial conditions drawn like the paper's (every angle and angular velocity uniform in +-IC_HALF_WIDTH, fixed
seed), unnormalized, the rest state as the equilibrium, velocities the exact field (theta_dot, theta_ddot) at the
samples, as in the paper's data. The default damping is calibrated so that the last of the 7 demonstrations arrives
within ARRIVAL_RADIUS of the rest state (metrics.py's arrival criterion, full-state norm) at ARRIVAL_FRACTION of the
duration: every demonstration has settled before its end (their energies differ, so the others arrive earlier). Demonstrations are generated by `generate_npend` (experiments/elcd/download_data.sh) and cached under
NPEND_DIR; the loader only reads the cache.
"""
from __future__ import annotations

import json
import os
import re
import time
from typing import Dict, NamedTuple, Optional, Tuple

import numpy as np

NPEND_DIR = os.environ.get("ELCD_NPEND_DIR", "data/npend")   # the cache of the generated demonstrations
PAPER_DIR = os.environ.get("ELCD_PENDULUM_DIR", "data/pendulum")   # the pendulum data of the ELCD paper
PAPER_DT = 0.1                 # the paper's sampling step
DT = 0.005                     # the npend sampling step
SUBSTEPS = 10                  # RK4 sub-steps per sample
G = 9.81
BODIES = ("point", "rod")
DAMPING_MODELS = ("absolute", "joint")
N_DEMOS, N_TRAIN = 7, 3
IC_SEED = 0
IC_HALF_WIDTH = np.pi / 8      # the paper's initial angles and angular velocities: all 280 values of the 2-, 4-
                               # and 8-link data lie within +-0.39015 < pi / 8 = 0.39270 (under +-0.4 that would
                               # happen with probability 0.006)
ARRIVAL_RADIUS = 0.05          # metrics.ARRIVAL_RADIUS (not imported: metrics imports JAX)
ARRIVAL_FRACTION = 0.9         # the default damping puts the latest arrival at this fraction of the duration
SPEC_RE = re.compile(r"^(\d+)-N(\d+)(?:-b([0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?))?$")
# What fit_paper found on the paper's 2-, 4- and 8-link data (fit_pendulum, this file's entry point):
# point masses at the link ends, absolute damping, every link of length 1 and mass 1, g 9.81 and
# b 0.3 reproduce the paper's accelerations to a relative residual of 2.7e-8, 2.5e-8 and 2.6e-8 at 2, 4 and 8 links
# (the float32 rounding of the files), with lengths, masses and damping free per link or uniform alike (fitted
# values 1 +- 5e-9, 0.3 +- 2e-9). Joint damping leaves 6.7, 3.8 and 2.4 percent, uniform rods 12 to 32 percent.
# The paper's generator is this model; 'npend' extends it to any link count with the same rule.
PAPER_MODEL: Dict[str, object] = dict(body="point", damping_model="absolute", length_rule="1", mass_rule="1",
                                      g=G, damping=0.3, fitted=True,
                                      rel_residual={2: 2.657e-8, 4: 2.520e-8, 8: 2.626e-8})


class PendulumParams(NamedTuple):
    lengths: np.ndarray        # (n,) link lengths
    masses: np.ndarray         # (n,) link (rod) or end-point (point) masses
    g: float
    damping: float             # b
    body: str                  # "point" | "rod"
    damping_model: str         # "absolute" | "joint"

    @property
    def n(self) -> int:
        return int(self.lengths.shape[0])


def params_for(n: int, damping: float, model: Optional[Dict[str, object]] = None) -> PendulumParams:
    """The pendulum of `model` (PAPER_MODEL by default) with n links: lengths by its length rule ("1/n": every
    link 1 / n long, total length 1; "1": every link 1 long), masses by its mass rule ("1": every mass 1; "1/n")."""
    model = PAPER_MODEL if model is None else model
    rules = {"1/n": 1.0 / n, "1": 1.0}
    if model["length_rule"] not in rules or model["mass_rule"] not in rules:
        raise ValueError(f"unknown rule in {model}")
    return PendulumParams(np.full(n, rules[model["length_rule"]]), np.full(n, rules[model["mass_rule"]]),
                          float(model["g"]), float(damping), str(model["body"]), str(model["damping_model"]))


# ----------------------------------------------------------------------------- dynamics

def mass_coefficients(masses: np.ndarray, body: str) -> Tuple[np.ndarray, np.ndarray]:
    """(W (n, n), w (n,)) of the module docstring for point masses or uniform rods."""
    m = np.asarray(masses, np.float64)
    n = m.shape[0]
    idx = np.maximum(np.arange(n)[:, None], np.arange(n)[None, :])          # max(i, j)
    after = np.concatenate([np.cumsum(m[::-1])[::-1][1:], [0.0]])          # nu_i = sum_{k > i} m_k
    if body == "point":
        tail = after + m                                                    # mu_i = sum_{k >= i} m_k
        return tail[idx], tail
    if body == "rod":
        W = m[idx] / 2.0 + after[idx]
        W[np.diag_indices(n)] = m / 3.0 + after
        return W, m / 2.0 + after
    raise ValueError(f"body must be one of {BODIES}, got {body!r}")


def damping_forces(omega: np.ndarray, p: PendulumParams) -> np.ndarray:
    """R(theta_dot) (..., n) of the module docstring."""
    if p.damping_model == "absolute":
        return p.damping * omega
    if p.damping_model == "joint":
        rel = np.diff(omega, axis=-1, prepend=0.0)                          # w_i - w_{i-1}, w_0 = 0
        nxt = np.concatenate([rel[..., 1:], np.zeros_like(rel[..., :1])], axis=-1)
        return p.damping * (rel - nxt)
    raise ValueError(f"damping model must be one of {DAMPING_MODELS}, got {p.damping_model!r}")


def mass_matrix(theta: np.ndarray, p: PendulumParams) -> np.ndarray:
    """M(theta) (..., n, n)."""
    W, _ = mass_coefficients(p.masses, p.body)
    LL = p.lengths[:, None] * p.lengths[None, :]
    return W * LL * np.cos(theta[..., :, None] - theta[..., None, :])


def accelerations(theta: np.ndarray, omega: np.ndarray, p: PendulumParams) -> np.ndarray:
    """theta_ddot (..., n) = -M^{-1} (C theta_dot^2 + G + R)."""
    W, w = mass_coefficients(p.masses, p.body)
    LL = p.lengths[:, None] * p.lengths[None, :]
    diff = theta[..., :, None] - theta[..., None, :]
    M = W * LL * np.cos(diff)
    C = np.einsum("...ij,...j->...i", W * LL * np.sin(diff), omega ** 2)
    rhs = -(C + p.g * w * p.lengths * np.sin(theta) + damping_forces(omega, p))
    return np.linalg.solve(M, rhs[..., None])[..., 0]


def field(x: np.ndarray, p: PendulumParams) -> np.ndarray:
    """The first-order field (theta_dot, theta_ddot) at states x (..., 2 n)."""
    n = p.n
    return np.concatenate([x[..., n:], accelerations(x[..., :n], x[..., n:], p)], axis=-1)


def energy(x: np.ndarray, p: PendulumParams) -> np.ndarray:
    """E = T + V at states x (..., 2 n), V = 0 at rest."""
    n = p.n
    theta, omega = x[..., :n], x[..., n:]
    _, w = mass_coefficients(p.masses, p.body)
    T = 0.5 * np.einsum("...i,...ij,...j->...", omega, mass_matrix(theta, p), omega)
    V = p.g * np.sum(w * p.lengths * (1.0 - np.cos(theta)), axis=-1)
    return T + V


def simulate(x0: np.ndarray, p: PendulumParams, dt: float, n_samples: int, substeps: int = SUBSTEPS) -> np.ndarray:
    """Classical RK4 at step dt / substeps from x0 (B, 2 n), sampled every dt: (B, n_samples, 2 n), x0 first."""
    h = dt / substeps
    x = np.asarray(x0, np.float64).copy()
    out = np.empty((x.shape[0], n_samples, x.shape[1]))
    out[:, 0] = x
    for k in range(1, n_samples):
        for _ in range(substeps):
            k1 = field(x, p)
            k2 = field(x + 0.5 * h * k1, p)
            k3 = field(x + 0.5 * h * k2, p)
            k4 = field(x + h * k3, p)
            x = x + (h / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        out[:, k] = x
    return out


def initial_conditions(n: int, count: int = N_DEMOS, seed: int = IC_SEED, half_width: float = IC_HALF_WIDTH) -> np.ndarray:
    """(count, 2 n): every angle and angular velocity uniform in +-half_width (the paper's range)."""
    rng = np.random.default_rng([seed, n])
    return rng.uniform(-half_width, half_width, size=(count, 2 * n))


def arrival_fraction(X: np.ndarray, dt: float, radius: float = ARRIVAL_RADIUS) -> np.ndarray:
    """Per trajectory (B, N, D): the first time within radius of the rest state (full-state norm) over the
    duration; inf when it never arrives."""
    near = np.linalg.norm(X, axis=-1) < radius
    first = np.where(near.any(axis=1), near.argmax(axis=1), -1)
    duration = (X.shape[1] - 1) * dt
    return np.where(first >= 0, first * dt / duration, np.inf)


# ----------------------------------------------------------------------------- the paper's data

def load_paper(n: int, paper_dir: Optional[str] = None) -> Tuple[np.ndarray, np.ndarray]:
    """(X, Xdot) of the paper's n-link data as float64 (T, n_demos, 2 n)."""
    with np.load(os.path.join(PAPER_DIR if paper_dir is None else paper_dir, f"n-{n}.npz")) as data:
        return np.asarray(data["my_X_phy"], np.float64), np.asarray(data["my_X_dot_phy"], np.float64)


def _unpack(z: np.ndarray, n: int, body: str, damping_model: str, uniform: bool, g: float) -> PendulumParams:
    """Parameters from the fit vector: log lengths (1 or n), log masses of links 2.. (0 or n - 1; link 1 has mass
    1), log damping."""
    if uniform:
        lengths, masses, b = np.full(n, np.exp(z[0])), np.ones(n), np.exp(z[1])
    else:
        lengths = np.exp(z[:n])
        masses = np.concatenate([[1.0], np.exp(z[n: 2 * n - 1])])
        b = np.exp(z[2 * n - 1])
    return PendulumParams(lengths, masses, g, float(b), body, damping_model)


def fit_paper(n: int, body: str, damping_model: str, uniform: bool = False, g: float = G,
              paper_dir: Optional[str] = None, starts: Tuple[Tuple[float, float], ...] = ((1.0, 0.1), (1.0, 1.0), (0.3, 0.03))
              ) -> Dict[str, object]:
    """Least squares on the acceleration residual theta_ddot_model(x) - theta_ddot_data over every sample of the
    paper's n-link data, from several starts (length factor times 1 / n, damping); the best of them. Returns the
    parameters, the relative residual |r| / |theta_ddot| and the kinematic check max|Xdot[:n] - X[n:]|."""
    from scipy.optimize import least_squares
    X, Xd = load_paper(n, paper_dir)
    theta, omega, acc = X[..., :n], X[..., n:], Xd[..., n:]
    kin = float(np.max(np.abs(Xd[..., :n] - omega)))
    scale = float(np.linalg.norm(acc))

    def residual(z):
        p = _unpack(z, n, body, damping_model, uniform, g)
        return (accelerations(theta, omega, p) - acc).ravel() / scale

    best = None
    for lf, b0 in starts:
        z0 = [np.log(lf / n), np.log(b0)] if uniform else list(np.full(n, np.log(lf / n))) + [0.0] * (n - 1) + [np.log(b0)]
        res = least_squares(residual, np.asarray(z0), method="trf", x_scale="jac", xtol=1e-14, ftol=1e-14, gtol=1e-14,
                            max_nfev=2000)
        if best is None or res.cost < best.cost:
            best = res
    p = _unpack(best.x, n, body, damping_model, uniform, g)
    return dict(n=n, body=body, damping_model=damping_model, uniform=uniform, rel_residual=float(np.sqrt(2 * best.cost)),
                lengths=p.lengths.tolist(), masses=p.masses.tolist(), damping=p.damping, g=g, kinematic_check=kin,
                success=bool(best.success), nfev=int(best.nfev))


# ----------------------------------------------------------------------------- npend demonstrations

def fit_pendulum() -> None:
    """Fit every body and damping model, per-link and uniform parameters, to the paper's 2-, 4- and 8-link data;
    prints one JSON line per fit and the paper's initial-condition range."""
    ics = []
    for n in (2, 4, 8):
        X, _ = load_paper(n)
        ics.append(np.abs(X[0]).ravel())
        print(f"n {n}: initial |theta|, |theta_dot| max {np.abs(X[0]).max():.5f}; dt {PAPER_DT}; "
              f"T {X.shape[0]}, demos {X.shape[1]}", flush=True)
    print(f"initial conditions: max |value| over all {np.concatenate(ics).size} values {np.concatenate(ics).max():.5f} "
          f"(pi/8 = {np.pi / 8:.5f})", flush=True)
    for n in (2, 4, 8):
        for body in BODIES:
            for model in DAMPING_MODELS:
                for uniform in (True, False):
                    t0 = time.time()
                    r = fit_paper(n, body, model, uniform=uniform)
                    r["seconds"] = round(time.time() - t0, 1)
                    print(json.dumps(r), flush=True)


class NpendSpec(NamedTuple):
    links: int
    N: int
    damping: Optional[float]   # None: the calibrated default


def parse_spec(body: str) -> NpendSpec:
    """'<links>-N<n>[-b<damping>]' -> NpendSpec."""
    m = SPEC_RE.match(body)
    if not m:
        raise ValueError(f"npend spec must be '<links>-N<n>[-b<damping>]', got {body!r}")
    links, N = int(m.group(1)), int(m.group(2))
    if links < 1 or N < 2:
        raise ValueError(f"npend needs links >= 1 and N >= 2, got {body!r}")
    return NpendSpec(links, N, None if m.group(3) is None else float(m.group(3)))


def cache_name(spec: NpendSpec) -> str:
    return f"{spec.links}-N{spec.N}" + ("" if spec.damping is None else f"-b{spec.damping:g}")


def calibrate_damping(links: int, N: int, x0: np.ndarray, model: Optional[Dict[str, object]] = None,
                      target: float = ARRIVAL_FRACTION, grid: int = 12, rounds: int = 3, dt: float = DT
                      ) -> Tuple[float, Dict[str, object]]:
    """The damping on the underdamped branch whose last demonstration arrives at `target` of the duration: a log
    grid of b simulated in one batch, then `rounds` finer grids inside the bracket where the latest arrival fraction
    crosses the target from above (the smallest such b). The distance to rest oscillates with every swing, so the
    first arrival can jump by half a swing as b changes; the result then sits at the jump, on the side where every
    demonstration has arrived, below the target. Returns (b, a log of the rounds)."""
    lo, hi = 1e-4, 1e2
    log = []
    b_best = None
    for r in range(rounds + 1):
        bs = np.geomspace(lo, hi, grid)
        X = simulate(np.concatenate([x0] * grid), _batched(links, bs, x0.shape[0], model), dt, N)
        frac = arrival_fraction(X, dt).reshape(grid, x0.shape[0])
        latest = frac.max(axis=1)
        log.append(dict(round=r, b=bs.tolist(), latest_fraction=latest.tolist()))
        below = np.nonzero(latest <= target)[0]
        if below.size == 0:
            raise ValueError(f"npend {links} links, N {N}: no damping in [{lo:g}, {hi:g}] arrives by {target} of the duration")
        k = int(below[0])
        if k == 0:
            b_best = float(bs[0])
            break
        lo, hi = float(bs[k - 1]), float(bs[k])
        b_best = hi
    return b_best, dict(rounds=log)


class _Batched(NamedTuple):
    """A pendulum whose damping differs across a batch of trajectories (the calibration grid)."""
    lengths: np.ndarray
    masses: np.ndarray
    g: float
    damping: np.ndarray        # (B, 1)
    body: str
    damping_model: str

    @property
    def n(self) -> int:
        return int(self.lengths.shape[0])


def _batched(links: int, bs: np.ndarray, per: int, model: Optional[Dict[str, object]]) -> _Batched:
    base = params_for(links, 0.0, model)
    return _Batched(base.lengths, base.masses, base.g, np.repeat(np.asarray(bs, np.float64), per)[:, None], base.body,
                    base.damping_model)


def generate_npend(body: str, cache_dir: Optional[str] = None, model: Optional[Dict[str, object]] = None) -> str:
    """Simulate and cache the demonstrations of spec body '<links>-N<n>[-b<damping>]'; returns the cache path."""
    spec = parse_spec(body)
    x0 = initial_conditions(spec.links)
    info: Dict[str, object] = {}
    b = spec.damping
    if b is None:
        b, info = calibrate_damping(spec.links, spec.N, x0, model)
    p = params_for(spec.links, b, model)
    X = simulate(x0, p, DT, spec.N)
    V = field(X, p)
    E = energy(X, p)
    cache_dir = NPEND_DIR if cache_dir is None else cache_dir
    os.makedirs(cache_dir, exist_ok=True)
    path = os.path.join(cache_dir, cache_name(spec) + ".npz")
    np.savez(path, pos=X, vel=V, energy=E, dt=np.float64(DT), x0=x0, lengths=p.lengths, masses=p.masses,
             g=np.float64(p.g), damping=np.float64(p.damping), body=np.array(p.body),
             damping_model=np.array(p.damping_model), substeps=np.int64(SUBSTEPS),
             arrival_fraction=arrival_fraction(X, DT), calibration=np.array(repr(info)), spec=np.array(body))
    return path


def load_npend(body: str, cache_dir: Optional[str] = None):
    """Demos of spec body '<links>-N<n>[-b<damping>]' from the cache (numpy only; cache_dir None: NPEND_DIR at call
    time)."""
    from experiments.elcd.train.data import Demos
    spec = parse_spec(body)
    path = os.path.join(NPEND_DIR if cache_dir is None else cache_dir, cache_name(spec) + ".npz")
    if not os.path.exists(path):
        raise FileNotFoundError(f"{path} is missing: generate it with experiments/elcd/download_data.sh (8-N5000) or "
                                f"with pendulum.generate_npend")
    with np.load(path, allow_pickle=False) as data:
        pos, vel, dt = np.asarray(data["pos"]), np.asarray(data["vel"]), float(data["dt"])
    D = pos.shape[2]
    name = f"npend:{spec.links}-N{spec.N}" + ("" if spec.damping is None else f"-b{spec.damping:g}")
    return Demos(name, pos, vel, dt, np.zeros(D), N_TRAIN, np.ones(D), ((0, int(pos.shape[1]), name),),
                 tuple(0 for _ in range(pos.shape[0])))


